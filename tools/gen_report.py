def stats_by_speciality():
    spec_names = {s["КодСпециальности"]: s["НазваниеСпециальности"] for s in DATA["Специальности"]}
    doc_spec = {d["КодВрача"]: d["КодСпециальности"] for d in DATA["Врачи"]}
    st = defaultdict(lambda: {"Всего": 0, "Проведён": 0, "Запланирован": 0,
                              "Неявка": 0, "Отменён": 0})
    for z in DATA["ЗаписиНаПриём"]:
        name = spec_names[doc_spec[z["КодВрача"]]]
        st[name]["Всего"] += 1
        st[name][z["СтатусЗаписи"]] += 1
    order = [s["НазваниеСпециальности"] for s in
             sorted(DATA["Специальности"], key=lambda x: x["ПорядокОтображения"])]
    return [(n, st[n]["Всего"], st[n]["Проведён"], st[n]["Запланирован"],
             st[n]["Неявка"], st[n]["Отменён"]) for n in order]


def stats_by_doctor(top=6):
    docs = {d["КодВрача"]: "%s %s. %s." % (d["Фамилия"], d["Имя"][0], d["Отчество"][0])
            for d in DATA["Врачи"]}
    st = defaultdict(lambda: [0, 0])
    for z in DATA["ЗаписиНаПриём"]:
        st[z["КодВрача"]][0] += 1
        if z["СтатусЗаписи"] == "Проведён":
            st[z["КодВрача"]][1] += 1
    rows = sorted(st.items(), key=lambda kv: -kv[1][0])
    return [(docs[k], v[0], v[1]) for k, v in rows[:top]]


def total_cost():
    srv = {s["КодУслуги"]: float(s["Стоимость"]) for s in DATA["Услуги"]}
    return sum(float(n["Количество"]) * srv[n["КодУслуги"]] for n in DATA["Назначения"])


def _remove_table_borders(table):
    tblPr = table._tbl.tblPr
    borders = OxmlElement("w:tblBorders")
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        e = OxmlElement("w:" + edge)
        e.set(qn("w:val"), "none")
        e.set(qn("w:sz"), "0")
        e.set(qn("w:space"), "0")
        e.set(qn("w:color"), "auto")
        borders.append(e)
    tblPr.append(borders)


