def build():
    H.COUNTERS["табл"] = 0
    H.COUNTERS["рис"] = 0
    H.COUNTERS["форм"] = 0

    doc = Document()
    H.set_base_style(doc)

    # ---------- СЕКЦИЯ 1: ТИТУЛЬНЫЙ ЛИСТ (п. 1.1.1 и 1.11: поля 2,5/1,5/2,0/2,0 см, без рамки) ----------
    sec0 = doc.sections[0]
    H.set_margins(sec0, left=2.5, right=1.5, top=2.0, bottom=2.0)
    sec0.footer.is_linked_to_previous = False
    sec0.header.is_linked_to_previous = False
    for p in list(sec0.footer.paragraphs):
        p._element.getparent().remove(p._element)
    for p in list(sec0.header.paragraphs):
        p._element.getparent().remove(p._element)

    title_page(doc)

    # ---------- СЕКЦИЯ 2: СОДЕРЖАНИЕ (п. 1.1.2 и 1.12.2: поля 3,0/1,5/1,5/5,5 см, штамп 40 мм) ----------
    sec1 = doc.add_section(WD_SECTION.NEW_PAGE)
    H.set_margins(sec1, left=3.0, right=1.5, top=1.5, bottom=5.5, footer_dist=0.5)
    H.add_page_borders(sec1)
    H.add_stamp_40(doc, sec1, total_pages=37)
    sec1.header.is_linked_to_previous = False
    for p in list(sec1.header.paragraphs):
        p._element.getparent().remove(p._element)

    toc_page(doc)

    # ---------- СЕКЦИЯ 3: ОСНОВНОЙ ТЕКСТ (п. 1.1.3 и 1.12.1: поля 2,5/1,5/1,5/2,5 см, штамп 15 мм) ----------
    sec2 = doc.add_section(WD_SECTION.NEW_PAGE)
    H.set_margins(sec2, left=2.5, right=1.5, top=1.5, bottom=2.5, footer_dist=0.5)
    H.add_page_borders(sec2)
    H.add_stamp_15(doc, sec2)
    sec2.header.is_linked_to_previous = False
    for p in list(sec2.header.paragraphs):
        p._element.getparent().remove(p._element)

    introduction(doc)
    chapter1(doc)
    chapter2(doc)
    chapter3(doc)
    chapter4(doc)
    conclusion(doc)
    references(doc)
    appendix_a(doc)
    appendix_b(doc)
    appendix_v(doc)
    appendix_g(doc)

    out = os.path.join(OUT_DIR, "Отчёт_Практика_АБД_Поликлиника_Сагадиев.docx")
    doc.save(out)
    print("Отчёт сохранён:", out)
    print("Таблиц:", H.COUNTERS["табл"], "| Рисунков:", H.COUNTERS["рис"], "| Формул:", H.COUNTERS["форм"])
    return out


if __name__ == "__main__":
    build()
