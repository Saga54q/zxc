' Врачи -> Специальности (при удалении: CASCADE)
ALTER TABLE [Врачи] ADD CONSTRAINT FK_Врачи_Специальности FOREIGN KEY ([КодСпециальности]) REFERENCES [Специальности] ([КодСпециальности]);
' Услуги -> Специальности (при удалении: CASCADE)
ALTER TABLE [Услуги] ADD CONSTRAINT FK_Услуги_Специальности FOREIGN KEY ([КодСпециальности]) REFERENCES [Специальности] ([КодСпециальности]);
' РасписаниеПриёма -> Врачи (при удалении: CASCADE)
ALTER TABLE [РасписаниеПриёма] ADD CONSTRAINT FK_Расписание_Врачи FOREIGN KEY ([КодВрача]) REFERENCES [Врачи] ([КодВрача]);
' ЗаписиНаПриём -> Пациенты (при удалении: CASCADE)
ALTER TABLE [ЗаписиНаПриём] ADD CONSTRAINT FK_Записи_Пациенты FOREIGN KEY ([КодПациента]) REFERENCES [Пациенты] ([КодПациента]);
' ЗаписиНаПриём -> Врачи (при удалении: CASCADE)
ALTER TABLE [ЗаписиНаПриём] ADD CONSTRAINT FK_Записи_Врачи FOREIGN KEY ([КодВрача]) REFERENCES [Врачи] ([КодВрача]);
' ЗаписиНаПриём -> РасписаниеПриёма (при удалении: SET NULL)
ALTER TABLE [ЗаписиНаПриём] ADD CONSTRAINT FK_Записи_Расписание FOREIGN KEY ([КодРасписания]) REFERENCES [РасписаниеПриёма] ([КодРасписания]);
' Диагнозы -> ЗаписиНаПриём (при удалении: CASCADE)
ALTER TABLE [Диагнозы] ADD CONSTRAINT FK_Диагнозы_Записи FOREIGN KEY ([КодЗаписи]) REFERENCES [ЗаписиНаПриём] ([КодЗаписи]);
' Диагнозы -> МКБ (при удалении: CASCADE)
ALTER TABLE [Диагнозы] ADD CONSTRAINT FK_Диагнозы_МКБ FOREIGN KEY ([КодМКБ]) REFERENCES [МКБ] ([КодМКБ]);
' Назначения -> ЗаписиНаПриём (при удалении: CASCADE)
ALTER TABLE [Назначения] ADD CONSTRAINT FK_Назначения_Записи FOREIGN KEY ([КодЗаписи]) REFERENCES [ЗаписиНаПриём] ([КодЗаписи]);
' Назначения -> Услуги (при удалении: CASCADE)
ALTER TABLE [Назначения] ADD CONSTRAINT FK_Назначения_Услуги FOREIGN KEY ([КодУслуги]) REFERENCES [Услуги] ([КодУслуги]);
' Пользователи -> Роли (при удалении: CASCADE)
ALTER TABLE [Пользователи] ADD CONSTRAINT FK_Пользователи_Роли FOREIGN KEY ([КодРоли]) REFERENCES [Роли] ([КодРоли]);
' Пользователи -> Врачи (при удалении: SET NULL)
ALTER TABLE [Пользователи] ADD CONSTRAINT FK_Пользователи_Врачи FOREIGN KEY ([КодВрача]) REFERENCES [Врачи] ([КодВрача]);

