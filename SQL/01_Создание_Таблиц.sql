' --- 01. СОЗДАНИЕ ТАБЛИЦ (Jet/ACE SQL DDL) -------------------------

' Специальности. Справочник врачебных специальностей поликлиники
' Ограничение CK_Spec_Name: CHECK (Len([НазваниеСпециальности]) >= 3)
CREATE TABLE [Специальности] (
    [КодСпециальности] COUNTER CONSTRAINT PK_Специальности PRIMARY KEY,
    [НазваниеСпециальности] TEXT(60) NOT NULL UNIQUE,
    [Описание] MEMO,
    [ПорядокОтображения] LONG
);

' Врачи. Справочник врачей поликлиники
' Ограничение CK_Vrach_Kab: CHECK (Len([Кабинет]) >= 1)
CREATE TABLE [Врачи] (
    [КодВрача] COUNTER CONSTRAINT PK_Врачи PRIMARY KEY,
    [Фамилия] TEXT(40) NOT NULL,
    [Имя] TEXT(40) NOT NULL,
    [Отчество] TEXT(40),
    [КодСпециальности] LONG NOT NULL,
    [Кабинет] TEXT(10),
    [Телефон] TEXT(20),
    [ДатаПриёмаНаРаботу] DATETIME,
    [Категория] TEXT(30)
);

' Пациенты. Картотека пациентов поликлиники
' Ограничение CK_Pac_Pol: CHECK ([Пол] In ('М','Ж'))
' Ограничение CK_Pac_Uch: CHECK ([Участок] Between 1 And 12)
CREATE TABLE [Пациенты] (
    [КодПациента] COUNTER CONSTRAINT PK_Пациенты PRIMARY KEY,
    [Фамилия] TEXT(40) NOT NULL,
    [Имя] TEXT(40) NOT NULL,
    [Отчество] TEXT(40),
    [ДатаРождения] DATETIME NOT NULL,
    [Пол] TEXT(1) NOT NULL,
    [Адрес] TEXT(120),
    [Телефон] TEXT(20),
    [НомерПолиса] TEXT(20) NOT NULL UNIQUE,
    [ДатаРегистрации] DATETIME,
    [Участок] LONG
);

' Услуги. Прейскурант медицинских услуг поликлиники
' Ограничение CK_Usl_Cost: CHECK ([Стоимость] >= 0)
' Ограничение CK_Usl_Dur: CHECK ([ДлительностьМинут] Between 5 And 180)
CREATE TABLE [Услуги] (
    [КодУслуги] COUNTER CONSTRAINT PK_Услуги PRIMARY KEY,
    [КодСпециальности] LONG NOT NULL,
    [НазваниеУслуги] TEXT(80) NOT NULL,
    [Стоимость] CURRENCY NOT NULL,
    [ДлительностьМинут] LONG
);

' МКБ. Справочник диагнозов МКБ-10 (сокращённая версия)
' Ограничение CK_MKB_Code: CHECK (Len([КодМКБ]) >= 3)
CREATE TABLE [МКБ] (
    [КодМКБ] TEXT(6) CONSTRAINT PK_МКБ PRIMARY KEY,
    [Наименование] TEXT(200) NOT NULL,
    [КлассЗаболеваний] TEXT(80)
);

' РасписаниеПриёма. Сетка талонов (слотов) приёма врачей
' Ограничение CK_Rasp_Time: CHECK ([ВремяОкончания] > [ВремяНачала])
' Ограничение CK_Rasp_Day: CHECK ([ДатаПриёма] >= #01/01/2024#)
CREATE TABLE [РасписаниеПриёма] (
    [КодРасписания] COUNTER CONSTRAINT PK_РасписаниеПриёма PRIMARY KEY,
    [КодВрача] LONG NOT NULL,
    [ДатаПриёма] DATETIME NOT NULL,
    [ВремяНачала] DATETIME NOT NULL,
    [ВремяОкончания] DATETIME NOT NULL,
    [Кабинет] TEXT(10),
    [ДлительностьМинут] LONG,
    [ПризнакПриёма] YESNO
);

' ЗаписиНаПриём. Журнал записи пациентов на приём (талоны)
' Ограничение CK_Zap_Status: CHECK ([СтатусЗаписи] In ('Запланирован','Проведён','Отменён','Неявка'))
' Ограничение CK_Zap_Time: CHECK ([ВремяПриёма] >= #08:00:00# And [ВремяПриёма] <= #20:00:00#)
CREATE TABLE [ЗаписиНаПриём] (
    [КодЗаписи] COUNTER CONSTRAINT PK_ЗаписиНаПриём PRIMARY KEY,
    [НомерТалона] TEXT(20) NOT NULL UNIQUE,
    [КодПациента] LONG NOT NULL,
    [КодВрача] LONG NOT NULL,
    [КодРасписания] LONG,
    [ДатаПриёма] DATETIME NOT NULL,
    [ВремяПриёма] DATETIME NOT NULL,
    [СтатусЗаписи] TEXT(20) NOT NULL,
    [Жалобы] MEMO,
    [ДатаСоздания] DATETIME
);

' Диагнозы. Диагнозы, установленные в рамках приёма
' Ограничение CK_Diag_Type: CHECK ([ТипДиагноза] In ('Основной','Сопутствующий','Предварительный'))
CREATE TABLE [Диагнозы] (
    [КодДиагноза] COUNTER CONSTRAINT PK_Диагнозы PRIMARY KEY,
    [КодЗаписи] LONG NOT NULL,
    [КодМКБ] TEXT(6) NOT NULL,
    [ТипДиагноза] TEXT(20),
    [ДатаУстановки] DATETIME,
    [Примечание] TEXT(255)
);

' Назначения. Назначенные услуги, исследования и лечение
' Ограничение CK_Nazn_Qty: CHECK ([Количество] Between 1 And 50)
CREATE TABLE [Назначения] (
    [КодНазначения] COUNTER CONSTRAINT PK_Назначения PRIMARY KEY,
    [КодЗаписи] LONG NOT NULL,
    [КодУслуги] LONG NOT NULL,
    [Количество] LONG NOT NULL,
    [Дозировка] TEXT(60),
    [КратностьПрименения] TEXT(60),
    [ДатаНазначения] DATETIME,
    [Выполнено] YESNO
);

' Роли. Роли пользователей системы
' Ограничение CK_Role_Level: CHECK ([УровеньДоступа] Between 1 And 3)
CREATE TABLE [Роли] (
    [КодРоли] COUNTER CONSTRAINT PK_Роли PRIMARY KEY,
    [НазваниеРоли] TEXT(30) NOT NULL UNIQUE,
    [Описание] MEMO,
    [УровеньДоступа] LONG NOT NULL
);

' Пользователи. Учётные записи сотрудников (администрирование доступа)
' Ограничение CK_User_Login: CHECK (Len([Логин]) >= 3)
' Ограничение CK_User_Pwd: CHECK (Len([Пароль]) >= 5)
CREATE TABLE [Пользователи] (
    [КодПользователя] COUNTER CONSTRAINT PK_Пользователи PRIMARY KEY,
    [Логин] TEXT(30) NOT NULL UNIQUE,
    [Пароль] TEXT(40) NOT NULL,
    [ФИО] TEXT(80) NOT NULL,
    [КодРоли] LONG NOT NULL,
    [КодВрача] LONG,
    [Активен] YESNO
);

' АрхивЗаписей. Служебная таблица архива прошедших приёмов (заполняется запросом Q08)
CREATE TABLE [АрхивЗаписей] (
    [КодАрхива] COUNTER CONSTRAINT PK_АрхивЗаписей PRIMARY KEY,
    [КодЗаписи] LONG NOT NULL,
    [НомерТалона] TEXT(20),
    [КодПациента] LONG,
    [КодВрача] LONG,
    [ДатаПриёма] DATETIME,
    [ВремяПриёма] DATETIME,
    [СтатусЗаписи] TEXT(20),
    [Жалобы] MEMO,
    [ДатаАрхивации] DATETIME
);

' ЖурналСобытий. Журнал аудита действий пользователей
CREATE TABLE [ЖурналСобытий] (
    [КодСобытия] COUNTER CONSTRAINT PK_ЖурналСобытий PRIMARY KEY,
    [ДатаВремя] DATETIME,
    [Логин] TEXT(30),
    [Действие] TEXT(80),
    [ОбъектДействия] TEXT(80),
    [Результат] TEXT(30)
);

' --- 01.2. СВОЙСТВА ПОЛЕЙ (DAO, выполняется из VBA) ---------------
' Маски ввода, подписи столбцов, значения по умолчанию и условия на
' значение устанавливаются процедурой УстановитьСвойстваПолей() модуля
' AutoBuild.bas через объектную модель DAO.

' Таблица Специальности:
'   [НазваниеСпециальности].Caption = Специальность
'   [НазваниеСпециальности].ValidationRule = Len([НазваниеСпециальности]) >= 3
'   [НазваниеСпециальности].ValidationText = Название специальности должно содержать не менее 3 символов

' Таблица Врачи:
'   [Телефон].InputMask = 8\-900\-000\-00\-00;0;_
'   [Телефон].Caption = Телефон
'   [Кабинет].InputMask = ###;0;_
'   [Кабинет].Caption = Кабинет
'   [Кабинет].ValidationRule = Len([Кабинет]) >= 1
'   [Кабинет].ValidationText = Укажите номер кабинета
'   [Категория].DefaultValue = "Без категории"

' Таблица Пациенты:
'   [Пол].DefaultValue = "М"
'   [Пол].ValidationRule = In ("М";"Ж")
'   [Пол].ValidationText = Пол указывается буквой М или Ж
'   [Телефон].InputMask = 8\-900\-000\-00\-00;0;_
'   [НомерПолиса].InputMask = 0000\ 0000\ 0000;0;_
'   [НомерПолиса].Caption = Полис ОМС
'   [ДатаРождения].Format = Short Date
'   [ДатаРождения].Caption = Дата рождения
'   [ДатаРегистрации].Format = Short Date
'   [ДатаРегистрации].DefaultValue = Date()
'   [Участок].ValidationRule = Between 1 And 12
'   [Участок].ValidationText = Номер участка должен быть от 1 до 12

' Таблица Услуги:
'   [Стоимость].Format = # ##0.00
'   [Стоимость].Caption = Стоимость, руб.
'   [Стоимость].DefaultValue = 0
'   [Стоимость].ValidationRule = >=0
'   [Стоимость].ValidationText = Стоимость услуги не может быть отрицательной
'   [ДлительностьМинут].DefaultValue = 15
'   [ДлительностьМинут].ValidationRule = Between 5 And 180
'   [ДлительностьМинут].ValidationText = Длительность услуги от 5 до 180 минут

' Таблица МКБ:
'   [КодМКБ].InputMask = >L00.0;;_
'   [КодМКБ].Caption = Код МКБ-10

' Таблица РасписаниеПриёма:
'   [ДатаПриёма].Format = Short Date
'   [ВремяНачала].Format = Short Time
'   [ВремяНачала].Caption = Начало
'   [ВремяОкончания].Format = Short Time
'   [ВремяОкончания].Caption = Окончание
'   [ДлительностьМинут].DefaultValue = 30
'   [ПризнакПриёма].DefaultValue = True

' Таблица ЗаписиНаПриём:
'   [НомерТалона].Caption = № талона
'   [ДатаПриёма].Format = Short Date
'   [ДатаПриёма].Caption = Дата приёма
'   [ВремяПриёма].Format = Short Time
'   [ВремяПриёма].Caption = Время
'   [ВремяПриёма].ValidationRule = >= #08:00:00# And <= #20:00:00#
'   [ВремяПриёма].ValidationText = Время приёма должно быть с 08:00 до 20:00
'   [СтатусЗаписи].ValidationRule = In ("Запланирован";"Проведён";"Отменён";"Неявка")
'   [СтатусЗаписи].ValidationText = Допустимые статусы: Запланирован, Проведён, Отменён, Неявка
'   [СтатусЗаписи].DefaultValue = "Запланирован"
'   [ДатаСоздания].DefaultValue = Now()

' Таблица Диагнозы:
'   [ТипДиагноза].DefaultValue = "Основной"
'   [ТипДиагноза].ValidationRule = In ("Основной";"Сопутствующий";"Предварительный")
'   [ДатаУстановки].Format = Short Date

' Таблица Назначения:
'   [Количество].DefaultValue = 1
'   [Количество].ValidationRule = Between 1 And 50
'   [Количество].ValidationText = Количество должно быть от 1 до 50
'   [ДатаНазначения].Format = Short Date
'   [ДатаНазначения].DefaultValue = Date()
'   [Выполнено].DefaultValue = False

' Таблица Роли:
'   [УровеньДоступа].DefaultValue = 1
'   [УровеньДоступа].ValidationRule = Between 1 And 3

' Таблица Пользователи:
'   [Активен].DefaultValue = True

' Таблица АрхивЗаписей:
'   [ДатаАрхивации].Format = Short Date
'   [ДатаАрхивации].DefaultValue = Date()

' Таблица ЖурналСобытий:
'   [ДатаВремя].Format = General Date
'   [ДатаВремя].DefaultValue = Now()
'   [Результат].DefaultValue = "Успешно"
