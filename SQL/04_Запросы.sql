HAVING Count(ЗаписиНаПриём.КодЗаписи) > 1;

' Q15_СтатистикаПоСпециальностям — Итоговый
' Параметры: без параметров
' Итоговая статистика приёмов по специальностям — источник диаграммы загрузки поликлиники.
SELECT Специальности.НазваниеСпециальности AS Специальность,
       Count(ЗаписиНаПриём.КодЗаписи) AS [Всего записей],
       Sum(IIf([ЗаписиНаПриём].[СтатусЗаписи] = 'Проведён', 1, 0)) AS Принято,
       Sum(IIf([ЗаписиНаПриём].[СтатусЗаписи] = 'Запланирован', 1, 0)) AS Запланировано,
       Sum(IIf([ЗаписиНаПриём].[СтатусЗаписи] = 'Неявка', 1, 0)) AS Неявка
FROM (Специальности LEFT JOIN Врачи ON Специальности.КодСпециальности = Врачи.КодСпециальности)
     LEFT JOIN ЗаписиНаПриём ON Врачи.КодВрача = ЗаписиНаПриём.КодВрача
GROUP BY Специальности.НазваниеСпециальности, Специальности.ПорядокОтображения
ORDER BY Специальности.ПорядокОтображения;

