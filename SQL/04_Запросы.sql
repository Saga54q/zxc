      LEFT JOIN Пациенты ON ЗаписиНаПриём.КодПациента = Пациенты.КодПациента
WHERE Врачи.Фамилия = [Введите фамилию врача]
  AND РасписаниеПриёма.ДатаПриёма = [Введите дату]
ORDER BY РасписаниеПриёма.ВремяНачала;

