' Q14_КонтрольПересеченияВремени — Контрольный (выборка)
' Параметры: без параметров
' Контроль соблюдения требования «время приёма не может пересекаться у одного врача»: возвращает записи-дубли по врачу, дате и времени.
SELECT ЗаписиНаПриём.КодВрача AS [Код врача],
       ЗаписиНаПриём.ДатаПриёма AS Дата,
