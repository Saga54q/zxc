' Q13_НазначенияПриёма — Выборка с вычисляемыми полями
' Параметры: без параметров
' Лист назначений по приёму с расчётом стоимости каждой услуги.
SELECT Назначения.КодЗаписи AS КодЗаписи,
       ЗаписиНаПриём.НомерТалона AS [№ талона],
