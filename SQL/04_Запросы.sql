' Q01_СвободныеТалоны — Выборка с параметрами
' Параметры: [Введите специальность], [Введите дату приёма]
' Свободные талоны к врачу по выбранной специальности на выбранную дату (специфика задания). Талоны, на которые уже есть запись, не выводятся: это соответствует уникальному индексу IX_Zap_Vrach_Time, запрещающему пересечение времени приёма у одного врача.
PARAMETERS [Введите специальность] Text ( 255 ), [Введите дату приёма] DateTime;
SELECT Специальности.НазваниеСпециальности AS Специальность,
       [Врачи].[Фамилия] & ' ' & Left([Врачи].[Имя], 1) & '. ' & Left([Врачи].[Отчество], 1) & '.' AS Врач,
       РасписаниеПриёма.ДатаПриёма AS Дата,
       РасписаниеПриёма.ВремяНачала AS Начало,
       РасписаниеПриёма.ВремяОкончания AS Окончание,
       РасписаниеПриёма.Кабинет AS Каб,
       РасписаниеПриёма.КодРасписания AS КодСлота
FROM (РасписаниеПриёма INNER JOIN Врачи ON РасписаниеПриёма.КодВрача = Врачи.КодВрача)
     INNER JOIN Специальности ON Врачи.КодСпециальности = Специальности.КодСпециальности
WHERE Специальности.НазваниеСпециальности = [Введите специальность]
  AND РасписаниеПриёма.ДатаПриёма = [Введите дату приёма]
  AND РасписаниеПриёма.ПризнакПриёма = True
  AND NOT EXISTS (SELECT 1 FROM ЗаписиНаПриём
                  WHERE ЗаписиНаПриём.КодРасписания = РасписаниеПриёма.КодРасписания)
ORDER BY Врачи.Фамилия, РасписаниеПриёма.ВремяНачала;

' Q02_ИсторияПосещенийПациента — Параметрический
' Параметры: [Введите фамилию пациента]
' История посещений пациента по фамилии (специфика задания): приёмы, врачи, специальности, статусы, основной диагноз.
PARAMETERS [Введите фамилию пациента] Text ( 255 );
SELECT [Пациенты].[Фамилия] & ' ' & [Пациенты].[Имя] & ' ' & [Пациенты].[Отчество] AS Пациент,
       ЗаписиНаПриём.НомерТалона AS [№ талона],
       ЗаписиНаПриём.ДатаПриёма AS Дата,
       ЗаписиНаПриём.ВремяПриёма AS Время,
       [Врачи].[Фамилия] & ' ' & Left([Врачи].[Имя], 1) & '. ' & Left([Врачи].[Отчество], 1) & '.' AS Врач,
       Специальности.НазваниеСпециальности AS Специальность,
       ЗаписиНаПриём.СтатусЗаписи AS Статус,
       (SELECT First(Диагнозы.КодМКБ) FROM Диагнозы
         WHERE Диагнозы.КодЗаписи = ЗаписиНаПриём.КодЗаписи
           AND Диагнозы.ТипДиагноза = 'Основной') AS [Код МКБ],
       ЗаписиНаПриём.Жалобы AS Жалобы
FROM ((ЗаписиНаПриём INNER JOIN Пациенты ON ЗаписиНаПриём.КодПациента = Пациенты.КодПациента)
      INNER JOIN Врачи ON ЗаписиНаПриём.КодВрача = Врачи.КодВрача)
      INNER JOIN Специальности ON Врачи.КодСпециальности = Специальности.КодСпециальности
WHERE Пациенты.Фамилия = [Введите фамилию пациента]
ORDER BY ЗаписиНаПриём.ДатаПриёма DESC, ЗаписиНаПриём.ВремяПриёма DESC;

' Q03_ЖурналЗаписей — Выборка с вычисляемыми полями
' Параметры: без параметров
' Полный журнал записей на приём с вычисляемыми полями: ФИО пациента, ФИО врача, возраст пациента, форматированная дата.
SELECT ЗаписиНаПриём.НомерТалона AS [№ талона],
       ЗаписиНаПриём.ДатаПриёма AS Дата,
       Format([ЗаписиНаПриём].[ДатаПриёма], 'dd.mm.yyyy') AS ДатаТекст,
       ЗаписиНаПриём.ВремяПриёма AS Время,
       [Пациенты].[Фамилия] & ' ' & Left([Пациенты].[Имя], 1) & '. ' & Left([Пациенты].[Отчество], 1) & '.' AS Пациент,
       DateDiff('yyyy', [Пациенты].[ДатаРождения], Date()) AS Возраст,
       [Врачи].[Фамилия] & ' ' & Left([Врачи].[Имя], 1) & '. ' & Left([Врачи].[Отчество], 1) & '.' AS Врач,
       Специальности.НазваниеСпециальности AS Специальность,
       ЗаписиНаПриём.СтатусЗаписи AS Статус
FROM ((ЗаписиНаПриём INNER JOIN Пациенты ON ЗаписиНаПриём.КодПациента = Пациенты.КодПациента)
      INNER JOIN Врачи ON ЗаписиНаПриём.КодВрача = Врачи.КодВрача)
      INNER JOIN Специальности ON Врачи.КодСпециальности = Специальности.КодСпециальности
ORDER BY ЗаписиНаПриём.ДатаПриёма, ЗаписиНаПриём.ВремяПриёма;

' Q04_ПациентыСВозрастом — Выборка с вычисляемыми полями
' Параметры: без параметров
' Картотека пациентов с расчётом возраста и группы диспансерного наблюдения.
SELECT Пациенты.КодПациента AS Код,
       [Пациенты].[Фамилия] & ' ' & [Пациенты].[Имя] & ' ' & [Пациенты].[Отчество] AS Пациент,
       Пациенты.ДатаРождения AS [Дата рождения],
       DateDiff('yyyy', [Пациенты].[ДатаРождения], Date()) AS Возраст,
       Пациенты.Пол AS Пол,
       IIf(DateDiff('yyyy', [Пациенты].[ДатаРождения], Date()) >= 60, 'Старшая',
           IIf(DateDiff('yyyy', [Пациенты].[ДатаРождения], Date()) <= 17, 'Детская', 'Трудоспособная')) AS Группа,
       Пациенты.НомерПолиса AS [Полис ОМС],
       Пациенты.Телефон AS Телефон,
       Пациенты.Участок AS Участок
FROM Пациенты
ORDER BY Пациенты.Фамилия, Пациенты.Имя;

' Q05_ИтогиПоВрачам — Итоговый
' Параметры: без параметров
' Итоговый запрос: количество принятых пациентов по каждому врачу (всего, проведено, неявка, отменено).
SELECT [Врачи].[Фамилия] & ' ' & Left([Врачи].[Имя], 1) & '. ' & Left([Врачи].[Отчество], 1) & '.' AS Врач,
       Специальности.НазваниеСпециальности AS Специальность,
       Count(ЗаписиНаПриём.КодЗаписи) AS [Всего записей],
       Sum(IIf([ЗаписиНаПриём].[СтатусЗаписи] = 'Проведён', 1, 0)) AS Проведено,
       Sum(IIf([ЗаписиНаПриём].[СтатусЗаписи] = 'Неявка', 1, 0)) AS Неявка,
       Sum(IIf([ЗаписиНаПриём].[СтатусЗаписи] = 'Отменён', 1, 0)) AS Отменено,
       Sum(IIf([ЗаписиНаПриём].[СтатусЗаписи] = 'Запланирован', 1, 0)) AS Запланировано
FROM (Врачи INNER JOIN ЗаписиНаПриём ON Врачи.КодВрача = ЗаписиНаПриём.КодВрача)
     INNER JOIN Специальности ON Врачи.КодСпециальности = Специальности.КодСпециальности
GROUP BY [Врачи].[Фамилия] & ' ' & Left([Врачи].[Имя], 1) & '. ' & Left([Врачи].[Отчество], 1) & '.',
         Специальности.НазваниеСпециальности
ORDER BY Count(ЗаписиНаПриём.КодЗаписи) DESC;

' Q06_ЗагрузкаВрачейЗаПериод — Итоговый с параметрами
' Параметры: [Начало периода], [Конец периода]
' Загрузка врачей по специальностям за выбранный период — источник данных отчёта «Загрузка врачей» (специфика задания).
PARAMETERS [Начало периода] DateTime, [Конец периода] DateTime;
SELECT Специальности.НазваниеСпециальности AS Специальность,
       [Врачи].[Фамилия] & ' ' & Left([Врачи].[Имя], 1) & '. ' & Left([Врачи].[Отчество], 1) & '.' AS Врач,
       Count(ЗаписиНаПриём.КодЗаписи) AS [Всего талонов],
       Sum(IIf([ЗаписиНаПриём].[СтатусЗаписи] = 'Проведён', 1, 0)) AS Принято,
       Sum(IIf([ЗаписиНаПриём].[СтатусЗаписи] = 'Неявка', 1, 0)) AS Неявка,
       Sum(IIf([ЗаписиНаПриём].[СтатусЗаписи] = 'Отменён', 1, 0)) AS Отменено
FROM (ЗаписиНаПриём INNER JOIN Врачи ON ЗаписиНаПриём.КодВрача = Врачи.КодВрача)
     INNER JOIN Специальности ON Врачи.КодСпециальности = Специальности.КодСпециальности
WHERE ЗаписиНаПриём.ДатаПриёма Between [Начало периода] And [Конец периода]
GROUP BY Специальности.НазваниеСпециальности,
         [Врачи].[Фамилия] & ' ' & Left([Врачи].[Имя], 1) & '. ' & Left([Врачи].[Отчество], 1) & '.'
ORDER BY Специальности.НазваниеСпециальности, Count(ЗаписиНаПриём.КодЗаписи) DESC;

' Q07_СтоимостьЛечения — Итоговый с вычисляемыми полями
' Параметры: без параметров
' Стоимость лечения по каждому приёму: сумма назначенных услуг (вычисляемое поле [Количество] * [Стоимость]). Имя вычисляемого поля задано как [Сумма руб] (без запятой и точки): MS Access не допускает символы «.» и «,» в именах полей (ошибка 3126).
SELECT ЗаписиНаПриём.КодЗаписи AS [Код записи],
       ЗаписиНаПриём.НомерТалона AS [№ талона],
       [Пациенты].[Фамилия] & ' ' & Left([Пациенты].[Имя], 1) & '. ' & Left([Пациенты].[Отчество], 1) & '.' AS Пациент,
       [Врачи].[Фамилия] & ' ' & Left([Врачи].[Имя], 1) & '. ' & Left([Врачи].[Отчество], 1) & '.' AS Врач,
       ЗаписиНаПриём.ДатаПриёма AS Дата,
       Count(Назначения.КодНазначения) AS [Услуг назначено],
       Sum([Назначения].[Количество] * [Услуги].[Стоимость]) AS [Сумма руб]
FROM (((ЗаписиНаПриём INNER JOIN Назначения ON ЗаписиНаПриём.КодЗаписи = Назначения.КодЗаписи)
      INNER JOIN Услуги ON Назначения.КодУслуги = Услуги.КодУслуги)
      INNER JOIN Пациенты ON ЗаписиНаПриём.КодПациента = Пациенты.КодПациента)
      INNER JOIN Врачи ON ЗаписиНаПриём.КодВрача = Врачи.КодВрача
GROUP BY ЗаписиНаПриём.КодЗаписи, ЗаписиНаПриём.НомерТалона,
         [Пациенты].[Фамилия] & ' ' & Left([Пациенты].[Имя], 1) & '. ' & Left([Пациенты].[Отчество], 1) & '.',
         [Врачи].[Фамилия] & ' ' & Left([Врачи].[Имя], 1) & '. ' & Left([Врачи].[Отчество], 1) & '.',
         ЗаписиНаПриём.ДатаПриёма
ORDER BY Sum([Назначения].[Количество] * [Услуги].[Стоимость]) DESC;

' Q08_АрхивацияЗаписей — На добавление (INSERT INTO … SELECT)
' Параметры: без параметров
' Переносит прошедшие приёмы (датой ранее текущей и статусом «Проведён» или «Неявка») в таблицу АрхивЗаписей.
INSERT INTO АрхивЗаписей ( КодЗаписи, НомерТалона, КодПациента, КодВрача,
                  ДатаПриёма, ВремяПриёма, СтатусЗаписи, Жалобы, ДатаАрхивации )
SELECT ЗаписиНаПриём.КодЗаписи, ЗаписиНаПриём.НомерТалона, ЗаписиНаПриём.КодПациента,
       ЗаписиНаПриём.КодВрача, ЗаписиНаПриём.ДатаПриёма, ЗаписиНаПриём.ВремяПриёма,
       ЗаписиНаПриём.СтатусЗаписи, ЗаписиНаПриём.Жалобы, Date() AS ДатаАрхивации
FROM ЗаписиНаПриём
WHERE ЗаписиНаПриём.ДатаПриёма < Date()
  AND ЗаписиНаПриём.СтатусЗаписи In ('Проведён', 'Неявка');

' Q09_ОбновлениеСтатусаПроведён — На обновление (UPDATE)
' Параметры: без параметров
' Проставляет статус «Проведён» для всех записей с датой приёма ранее текущей, если статус остался «Запланирован».
UPDATE ЗаписиНаПриём
SET ЗаписиНаПриём.СтатусЗаписи = 'Проведён'
WHERE ЗаписиНаПриём.ДатаПриёма < Date()
  AND ЗаписиНаПриём.СтатусЗаписи = 'Запланирован';

' Q10_УдалениеОтменённыхЗаписей — На удаление (DELETE)
' Параметры: без параметров
' Удаляет отменённые записи старше 30 дней после очистки архива.
DELETE ЗаписиНаПриём.*
FROM ЗаписиНаПриём
WHERE ЗаписиНаПриём.СтатусЗаписи = 'Отменён'
  AND ЗаписиНаПриём.ДатаПриёма < Date() - 30;

' Q11_РасписаниеВрачаНаДату — Параметрический
' Параметры: [Введите фамилию врача], [Введите дату]
' Расписание конкретного врача на выбранную дату с отметкой о занятости талона.
PARAMETERS [Введите фамилию врача] Text ( 255 ), [Введите дату] DateTime;
SELECT РасписаниеПриёма.ВремяНачала AS Начало,
       РасписаниеПриёма.ВремяОкончания AS Окончание,
       РасписаниеПриёма.Кабинет AS Каб,
       [Пациенты].[Фамилия] & ' ' & Left([Пациенты].[Имя], 1) & '.' AS Пациент,
